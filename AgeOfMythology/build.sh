#!/usr/bin/env bash
# Build the statically recompiled game: aomx.exe and the DLLs that are lifted with it.
#
#   ./build.sh [host|aarch64] [--relift]
#
# host     native build with the system compiler      -> build/host/aom
# aarch64  cross build for Linux/arm64 (glibc)         -> build/aarch64/aom
#
# Each image is lifted into build/gen/<module>/ with lift.py --module, so its
# functions are f_<module>_<addr>; build/gen/images.c lists them for the runtime.
#
# Environment:
#   ORIG         directory with the installed game files (default: orig/)
#   AARCH64_CC   cross compiler (default: the batocera h616 buildroot gcc)
#   JOBS         parallel compile jobs (default: number of CPUs)
#   OPT          optimisation level for the lifted code (default -O1)
#   EXTRA_CFLAGS extra compiler flags for everything (e.g. -DRT_DYNAMIC_BASE)
#   LIFT_FLAGS   extra lifter flags (e.g. --no-flag-liveness)
#   NO_SDL       1 = build without SDL2 (headless only)
#   VARIANT      suffix for the output directories, to keep an experimental build
#                (other LIFT_FLAGS / EXTRA_CFLAGS) next to the normal one
set -euo pipefail

target="${1:-host}"
relift=0
[ "${2:-}" = "--relift" ] && relift=1

here="$(cd "$(dirname "$0")" && pwd)"
orig="${ORIG:-$here/orig}"
build="$here/build"
variant="${VARIANT:-}"
gen="$build/gen$variant"
out="$build/$target$variant"
jobs="${JOBS:-$(nproc)}"
opt="${OPT:--O1}"

# module  file             lift base (empty: the PE's own)   function list (optional)
# The EXE comes first: the runtime takes rt_images[0] as the program.
modules=(
    "aomx     aomx.exe       -           $build/survey/aomx.functions.csv"
    "msvcrt   msvcrt.dll     -           -"
    "msvcp60  msvcp60.dll    -           -"
    "rockall  rockalldll.dll -           -"
    "granny   granny.dll     0x10100000  -"
    "mss32    mss32.dll      -           -"
    "mp3dec   mp3dec.asi     -           -"
)

case "$target" in
host) cc="${CC:-gcc}" ;;
aarch64) cc="${AARCH64_CC:-/home/coleman/Developer/batocera.linux/output/h616/host/bin/aarch64-buildroot-linux-gnu-gcc}" ;;
*)
    echo "usage: $0 [host|aarch64] [--relift]" >&2
    exit 2
    ;;
esac
command -v "$cc" >/dev/null || { echo "compiler not found: $cc" >&2; exit 2; }

if [ "${NO_SDL:-0}" = 1 ]; then
    sdl_cflags="-DRT_NO_SDL"
    sdl_libs=""
elif [ "$target" = host ]; then
    sdl_cflags="$(sdl2-config --cflags)"
    sdl_libs="$(sdl2-config --libs)"
else
    sdl_cflags="-I$("$cc" -print-sysroot)/usr/include/SDL2 -D_REENTRANT"
    sdl_libs="-lSDL2"
fi

# ---- 1. lift each image (redone when the lifter or its inputs change)
mkdir -p "$gen" "$out/obj"
pids=()
for line in "${modules[@]}"; do
    read -r mod file rebase csv <<<"$line"
    pe="$orig/$file"
    [ -f "$pe" ] || { echo "not found: $pe (set ORIG)" >&2; exit 2; }
    [ "$csv" = - ] || [ -f "$csv" ] || csv=-
    dir="$gen/$mod"
    stamp="$dir/.stamp"
    need=$relift
    [ -f "$stamp" ] || need=1
    if [ "$need" = 0 ]; then
        for f in "$here"/lift/*.py "$pe" ${csv#-}; do
            [ "$f" -nt "$stamp" ] && need=1
        done
    fi
    [ "$need" = 1 ] || continue
    mkdir -p "$dir"
    args=(--pe "$pe" --module "$mod" --out "$dir")
    [ "$rebase" = - ] || args+=(--rebase "$rebase")
    [ "$csv" = - ] || args+=(--csv "$csv")
    echo "== lifting $file"
    # shellcheck disable=SC2086
    (python3 "$here/lift/lift.py" "${args[@]}" ${LIFT_FLAGS:-} >"$dir/lift.log" 2>&1 && touch "$stamp") &
    pids+=($!)
done
for p in "${pids[@]}"; do
    wait "$p" || { echo "lift failed; see $gen/*/lift.log" >&2; exit 1; }
done

{
    echo "/* Generated by build.sh: the lifted images, EXE first. */"
    echo '#include "rt.h"'
    for line in "${modules[@]}"; do read -r mod _ <<<"$line"; echo "extern const RtImageDesc rt_image_$mod;"; done
    echo "const RtImageDesc *const rt_images[] = {"
    for line in "${modules[@]}"; do read -r mod _ <<<"$line"; echo "    &rt_image_$mod,"; done
    echo "};"
    echo "const unsigned rt_nimages = ${#modules[@]};"
} >"$gen/images.c.new"
cmp -s "$gen/images.c.new" "$gen/images.c" 2>/dev/null && rm "$gen/images.c.new" || mv "$gen/images.c.new" "$gen/images.c"

# ---- 2. compile + link through ninja
cflags_common="-std=gnu11 -pthread -fno-strict-aliasing -fwrapv -fno-stack-protector -I$here/runtime ${EXTRA_CFLAGS:-}"
{
    echo "cc = $cc"
    echo "gen_cflags = $opt -foptimize-sibling-calls $cflags_common -w"
    echo "rt_cflags = -O2 -g $cflags_common $sdl_cflags -Wall -Wextra -Wno-unused-parameter"
    echo "rule gen"
    echo "  command = \$cc \$gen_cflags \$inc -c \$in -o \$out"
    echo "  description = CC \$out"
    echo "rule rt"
    echo "  command = \$cc \$rt_cflags -MMD -MF \$out.d -c \$in -o \$out"
    echo "  depfile = \$out.d"
    echo "  description = CC \$out"
    echo "rule link"
    echo "  command = \$cc -o \$out \$in -lm -pthread $sdl_libs"
    echo "  description = LINK \$out"
    objs=""
    for line in "${modules[@]}"; do
        read -r mod _ <<<"$line"
        for src in "$gen/$mod"/chunk_*.c "$gen/$mod/tables.c"; do
            o="obj/$mod/$(basename "${src%.c}").o"
            # the lifted code is written against cpu.h alone; only tables.c sees rt.h
            deps="$here/runtime/cpu.h $gen/$mod/funcs.h"
            [ "$(basename "$src")" = tables.c ] && deps="$deps $here/runtime/rt.h"
            echo "build $o: gen $src | $deps"
            echo "  inc = -I$gen/$mod"
            objs="$objs $o"
        done
    done
    echo "build obj/images.o: gen $gen/images.c | $here/runtime/rt.h"
    objs="$objs obj/images.o"
    for src in "$here"/runtime/*.c; do
        o="obj/rt_$(basename "${src%.c}").o"
        echo "build $o: rt $src"
        objs="$objs $o"
    done
    echo "build aom: link $objs"
    echo "default aom"
} >"$out/build.ninja"

echo "== compiling for $target with $cc ($opt, -j$jobs)"
t0=$(date +%s)
ninja -C "$out" -j "$jobs"
echo "== build took $(( $(date +%s) - t0 ))s -> $out/aom"
